-- Live updates: stream row changes on these tables to subscribed apps.
-- Realtime applies each subscriber's RLS SELECT policies, so riders only
-- receive changes for rows they can already read. Safe to re-run.

do $$
declare
  t text;
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;

  foreach t in array array['rides', 'bikes', 'follows'] loop
    if not exists (
      select 1
      from pg_publication_tables
      where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = t
    ) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end
$$;
